/** Records by name. */
export const NEEDS_CARD: Record<string, CardRecord> = Object.fromEntries(
  RECORDS.map((c) => [c.name, c]),
);

/** A record by name; throws on a name that is not here, so a typo fails loudly. */
export function needsCard(name: string): CardRecord {
  const c = NEEDS_CARD[name];
  if (!c) throw new Error(`no fixture "${name}"`);
  return c;
}
