/** Pack land records by name. */
export const LAND = Object.fromEntries(RECORDS.map((c) => [c.name, c])) as Record<
  string,
  CardRecord
>;

/** The record of one card by name; throws for a name not copied here. */
export function land(name: string): CardRecord {
  const c = LAND[name];
  if (!c) throw new Error(`no pack record for ${name}`);
  return c;
}
